package kr.co.metadata.crawler

import kotlin.test.*

class ProfileRegressionTest {
    private val first = "https://catalog.example/1"
    private val second = "https://catalog.example/2"
    private fun sample(url: String, selector: String) = ElementSelection(url, "h1", "Title", emptyMap(),
        listOf(SelectorCandidate(selector, 1, true, 88)))
    private fun wizard() = SelectorProfileWizard(first, EntityKind.TRACK, "Example").apply {
        recordFirstPage(CatalogField.TRACK_TITLE, sample(first, "article > h1.title"))
        beginSecondPage(second)
        recordSecondPage(CatalogField.TRACK_TITLE, sample(second, "article > h1.title"))
    }

    @Test fun `ancestor selectors generated by picker can generalize and extract`() {
        val profile = wizard().buildProfile()
        val values = DynamicProfileExtractor.extract(profile, "https://catalog.example/3",
            "<article><h1 class='title'>Third song</h1></article>")
        assertEquals("Third song", values.single().value)
    }

    @Test fun `changing verification page clears earlier verification`() {
        val wizard = wizard()
        wizard.beginSecondPage("https://catalog.example/3")
        assertTrue(wizard.verifiedFields.isEmpty())
        assertFailsWith<IllegalStateException> { wizard.buildProfile() }
    }

    @Test fun `failed reselection invalidates previous verified field`() {
        val wizard = wizard()
        assertFailsWith<IllegalArgumentException> {
            wizard.recordSecondPage(CatalogField.TRACK_TITLE, sample(second, "h1.other"))
        }
        assertFailsWith<IllegalStateException> { wizard.buildProfile() }
    }

    @Test fun `class selectors cannot extract form controls or editable text`() {
        val profile = wizard().buildProfile().copy(rules = listOf(SelectorRule(
            CatalogField.TRACK_TITLE, ".title", ExtractionMode.TEXT, confidence = .9,
            verifiedPageUrls = listOf(first, second),
        )))
        for (html in listOf("<textarea class='title'>private</textarea>",
            "<div contenteditable='true'><h1 class='title'>private</h1></div>",
            "<div class='title'><textarea>private</textarea></div>")) {
            assertTrue(DynamicProfileExtractor.extract(profile, first, html).isEmpty())
        }
    }

    @Test fun `profile schema versions cannot be silently misinterpreted`() {
        val json = SiteProfileCodec.encode(wizard().buildProfile()).replace("\"schemaVersion\": 1", "\"schemaVersion\": 2")
        assertFailsWith<IllegalArgumentException> { SiteProfileCodec.decode(json) }
    }

    @Test fun `year parser handles compact and day first dates without concatenating digits`() {
        assertEquals(2026, "20261013".yearOrNull())
        assertEquals(2026, "13.10.2026".yearOrNull())
        assertEquals(2026, "2026년 10월 13일".yearOrNull())
        assertNull("unknown".yearOrNull())
        assertNull("13/10".yearOrNull())
    }
}
